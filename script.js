/* =================================
   SHOW PROVIDERS
================================= */

function showProviders(service) {

    const providers = providerData[service];

    providerTitle.textContent = service + " Providers";

    providerSubtitle.textContent =
        "Choose a provider for your " + service.toLowerCase() + " problem.";

    providerGrid.innerHTML = "";


    if (!providers || providers.length === 0) {

        providerGrid.innerHTML = `
            <div class="empty-state">
                <h3>No providers found</h3>
                <p>
                    We don't have providers for this service yet.
                </p>
            </div>
        `;

    } else {

        providers.forEach(function (provider) {

            const card = document.createElement("div");

            card.className = "provider-card";

            card.innerHTML = `

                <div class="provider-top">

                    <div class="provider-avatar">
                        ${provider.name.charAt(0)}
                    </div>

                    <div>

                        <h3 class="provider-name">
                            ${provider.name}
                        </h3>

                        <span class="verified">
                            ✓ Verified Demo Provider
                        </span>

                    </div>

                </div>


                <div class="rating">
                    ⭐ ${provider.rating}
                </div>


                <div class="provider-info">
                    📍 ${provider.location}
                </div>


                <div class="provider-price">
                    💰 ${provider.price}
                </div>


                <button class="details-btn">
                    View Details →
                </button>

            `;


            const detailsButton =
                card.querySelector(".details-btn");


            detailsButton.addEventListener("click", function () {

                openProviderDetails(service, provider);

            });


            providerGrid.appendChild(card);

        });

    }


    providerSection.style.display = "block";


    providerSection.scrollIntoView({
        behavior: "smooth",
        block: "start"
    });

}


