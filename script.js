/* =================================
   FIND HELP
================================= */

findHelpBtn.addEventListener("click", function () {

    findSmartMatch();

});


function findSmartMatch() {

    const problem =
        problemInput.value.trim().toLowerCase();


    if (problem === "") {

        alert("Please describe your problem first.");

        return;

    }


    let matchedService = null;


    /*
        First check specific phrases.
        This helps prevent wrong matches.
    */

    for (const category of problemCategories) {

        for (const keyword of category.keywords) {

            if (problem.includes(keyword.toLowerCase())) {

                matchedService = category.service;

                break;

            }

        }

        if (matchedService) {
            break;
        }

    }


    if (matchedService) {

        showProviders(matchedService);

    } else {

        alert(
            "We couldn't identify the exact service yet.\n\n" +
            "Please choose a service category below."
        );

        document
            .getElementById("services")
            .scrollIntoView({
                behavior: "smooth"
            });

    }

}


/* =================================
   ENTER KEY SUPPORT
================================= */

problemInput.addEventListener("keydown", function (event) {

    if (event.key === "Enter" && !event.shiftKey) {

        event.preventDefault();

        findSmartMatch();

    }

});
